const dictionaries: Record<Locale, Messages> = { en, pl }

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  categoryLabel: (category: Pick<Category, 'id' | 'label'>) => string
  placeCountLabel: (count: number) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function interpolate(value: string, vars?: Record<string, string | number>) {
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

const categoryTranslations: Record<Locale, Record<string, string>> = {
  en: { eat: 'Eat', coffee: 'Coffee', drink: 'Drink', see: 'See', shop: 'Shop', stay: 'Stay', other: 'Other' },
  pl: { eat: 'Jedzenie', coffee: 'Kawa', drink: 'Drinki', see: 'Zobacz', shop: 'Zakupy', stay: 'Nocleg', other: 'Inne' },
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY)
      if (saved === 'pl' || saved === 'en') return saved
    } catch { /* Storage may be blocked; use the browser language. */ }
    return navigator.language.toLowerCase().startsWith('pl') ? 'pl' : 'en'
  })

  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, locale) }
    catch { /* Language still works for this visit. */ }
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, vars) => interpolate(dictionaries[locale][key] ?? dictionaries.en[key] ?? key, vars),
    categoryLabel: category => categoryTranslations[locale][category.id] ?? category.label,
    placeCountLabel: count => {
      if (locale === 'en') return count === 1 ? 'place' : 'places'
      if (count === 1) return 'miejsce'
      const mod10 = count % 10
      const mod100 = count % 100
      if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) return 'miejsca'
      return 'miejsc'
    },
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider')
  return context
}
